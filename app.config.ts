/// <reference types="node" />
// ^ This file runs in Node (Expo CLI), not in the app; TS 6 no longer auto-loads @types.
import { existsSync } from 'node:fs';

import type { ConfigContext, ExpoConfig } from 'expo/config';

/**
 * Dynamic Expo config. Values come from `.env` (loaded automatically by the
 * Expo CLI) so identifiers never need to be hard-coded or committed.
 */
const bundleId = process.env.APP_BUNDLE_ID ?? 'com.example.authexpofirebase';
const iosUrlScheme = process.env.GOOGLE_IOS_URL_SCHEME;

// Firebase native config. Kept at the project root (git-ignored), NOT in
// android/app, because android/ is regenerated by `expo prebuild`.
// On EAS, upload it as a file env var named GOOGLE_SERVICES_JSON.
const googleServicesFile = process.env.GOOGLE_SERVICES_JSON ?? './google-services.json';
const hasGoogleServicesFile = existsSync(googleServicesFile);

/**
 * Google Sign-In config plugin:
 * - With google-services.json (Firebase mode, no options): adds the
 *   com.google.gms.google-services Gradle plugin and copies the file into
 *   android/app during prebuild.
 * - Otherwise, with only an iOS URL scheme: iOS-only setup.
 * - Neither: omitted so `expo start` works before Google is set up.
 */
function googleSignInPlugin(): ExpoConfig['plugins'] {
  if (hasGoogleServicesFile) return ['@react-native-google-signin/google-signin'];
  if (iosUrlScheme) return [['@react-native-google-signin/google-signin', { iosUrlScheme }]];
  return [];
}

export default ({ config }: ConfigContext): ExpoConfig => ({
  ...config,
  name: 'Auth Expo Firebase',
  slug: 'reactnative-auth-expo-firebase',
  version: '1.0.0',
  scheme: 'authexpofirebase',
  orientation: 'portrait',
  icon: './assets/icon.png',
  userInterfaceStyle: 'light',
  ios: {
    supportsTablet: true,
    bundleIdentifier: bundleId,
  },
  android: {
    package: bundleId,
    ...(hasGoogleServicesFile ? { googleServicesFile } : {}),
    adaptiveIcon: {
      backgroundColor: '#E6F4FE',
      foregroundImage: './assets/android-icon-foreground.png',
      backgroundImage: './assets/android-icon-background.png',
      monochromeImage: './assets/android-icon-monochrome.png',
    },
    predictiveBackGestureEnabled: false,
  },
  web: {
    favicon: './assets/favicon.png',
  },
  plugins: [
    'expo-router',
    'expo-dev-client',
    ...googleSignInPlugin()!,
  ],
  experiments: {
    typedRoutes: true,
  },
});
